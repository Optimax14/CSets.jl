include("workloads.jl"); include("stats.jl"); include("CSetsGPU.jl"); using .CSetsGPU
B = instance(boolean())
function cmp(name, X, S, Y)
    D = decomposition(X, S; alg=MF())
    color(D, Y); RefSearch.color(D, Y)
    tn = minimum(@elapsed(color(D, Y)) for _ in 1:2)
    to = minimum(@elapsed(RefSearch.color(D, Y)) for _ in 1:2)
    P = CSetsGPU.prepare(D); CSetsGPU.color(P, Y)
    tg = minimum(@elapsed(CSetsGPU.color(P, Y)) for _ in 1:2)
    C = CSetsGPU.prepare_contract(D); hk = CSetsGPU.contract(C, Y)
    tk = hk === :wide ? Inf : minimum(@elapsed(CSetsGPU.contract(C, Y)) for _ in 1:2)
    println(rpad(name, 22), " cpu(new)=", round(tn, digits=4), " cpu(d2927d3)=", round(to, digits=4), " gpu levelsync=", round(tg, digits=4), " gpu contract=", round(tk, digits=4)); flush(stdout)
end
